  function readProgress() {
    try {
      const value = JSON.parse(localStorage.getItem(PROGRESS_KEY) || "{}");
      return value && typeof value === "object" ? value : {};
    } catch (_) { return {}; }
  }

  function saveProgress(value) {
    try { localStorage.setItem(PROGRESS_KEY, JSON.stringify(value)); } catch (_) {}
  }

  const libraries = Object.fromEntries(Object.entries(raw).map(([theme, groups]) => {
    const items = Object.entries(groups).flatMap(([type, entries]) => entries.map((entry, index) => {
      const separator = entry.indexOf("：");
      return {
        id: `${theme}_${type}_${index + 1}`,
        theme,
        type,
        typeName: typeNames[type],
        title: separator > 0 ? entry.slice(0, separator) : typeNames[type],
        text: separator > 0 ? entry.slice(separator + 1) : entry,
      };
    }));
    return [theme, items];
  }));

  function randomIndex(max) {
    if (max <= 1) return 0;
    if (globalThis.crypto?.getRandomValues) {
      const value = new Uint32Array(1); crypto.getRandomValues(value); return value[0] % max;
    }
    return Math.floor(Math.random() * max);
  }

  function next(theme, options = {}) {
    const all = libraries[theme] || libraries.sunny;
    const progress = readProgress();
    const key = theme;
    const validIds = new Set(all.map(item => item.id));
    let seen = Array.isArray(progress[key]) ? progress[key].filter(id => validIds.has(id)) : [];
    let remaining = all.filter(item => !seen.includes(item.id));
    if (!remaining.length) { seen = []; remaining = all; }
    const preferred = options.type && typeNames[options.type] ? remaining.filter(item => item.type === options.type) : [];
    const candidates = preferred.length ? preferred : remaining;
    const item = candidates[randomIndex(candidates.length)];
    progress[key] = [...seen, item.id]; saveProgress(progress);
    return { ...item, remaining: remaining.length - 1, total: all.length };
  }

  function counts() { return Object.fromEntries(Object.entries(libraries).map(([theme, items]) => [theme, items.length])); }

  window.FocusBeatThemeContent = { next, counts, all: theme => (libraries[theme] || []).map(item => ({ ...item })) };
